    rated_products = [product_categories[idx] for idx in rated_indices]

    scores = {}

    for prod_idx in rated_indices:
        product_id = product_categories[prod_idx]

        if product_id in product_similarity_df.index:
            similarities = product_similarity_df.loc[product_id]
            rating = user_row[prod_idx]

            for candidate, similarity in similarities.items():
                if candidate in rated_products or similarity == 0:
                    continue
                scores[candidate] = scores.get(candidate, 0) + similarity * rating

    result = sorted(scores.items(), key=lambda x: x[1], reverse=True)[:n]
